-- ----------------------------------------------------------------------------
-- خزنده سایت‌هایی رو که در مطالب مرتبط با حوزه بیشتر لینک داده شدن، با source='suggest'
-- به crawl_sites اضافه می‌کنه و از اجرای بعدی می‌گرده؛ مدیر در «تنظیمات بخش‌ها ← منابع
-- خزنده» تأیید (→ مدیریت منابع) یا متوقف (→ حذف از فهرست) می‌کنه.
-- اجرا: یک‌بار در SQL Editor سوپابیس. چند بار اجرا کردنش بی‌خطره.
-- ============================================================================

alter table crawl_sites drop constraint if exists crawl_sites_source_check;
alter table crawl_sites add constraint crawl_sites_source_check
  check (source in ('manual', 'channel', 'suggest'));
